#!/usr/bin/env bash
#
# sync-hub.sh — AI Configuration Hub Synchronization Script
#
# This script manages all symlink and file mapping logic between the centralized
# AI hub at ~/.config/ai/ and the consuming tools (OpenCode and VS Code).
#
# When to run:
#   - After adding, removing, or renaming skills, agents, or instructions
#   - After manually editing files in ~/.config/ai/
#   - As part of a dotfiles setup or post-pull hook
#   - Whenever you want to ensure all consumers are in sync with the hub
#
# Usage: ~/.config/ai/sync-hub.sh

set -euo pipefail

# ------------------------------------------------------------------------------
# Configuration
# ------------------------------------------------------------------------------

HUB_DIR="${HOME}/.config/ai"
OPENCODE_DIR="${HOME}/.config/opencode"
VSCODE_DIR="${HUB_DIR}/vscode"

# Track actions for summary report
declare -a CREATED=()
declare -a UPDATED=()
declare -a REMOVED=()
declare -a VERIFIED=()

# ------------------------------------------------------------------------------
# Helpers
# ------------------------------------------------------------------------------

log() {
    echo "[sync-hub] $*"
}

# Resolve a symlink to its ultimate target (one level is enough for our relative links)
get_link_target() {
    local link="$1"
    if [[ -L "$link" ]]; then
        readlink "$link"
    else
        echo ""
    fi
}

# Create a relative symlink from $1 (link path) to $2 (target path, relative to link dir)
# If a wrong symlink exists, update it. If a regular file exists, abort.
ensure_symlink() {
    local link_path="$1"
    local rel_target="$2"
    local link_dir
    link_dir="$(dirname "$link_path")"

    mkdir -p "$link_dir"

    if [[ -L "$link_path" ]]; then
        local current_target
        current_target="$(get_link_target "$link_path")"
        if [[ "$current_target" == "$rel_target" ]]; then
            VERIFIED+=("symlink $link_path -> $rel_target")
            return 0
        fi
        rm "$link_path"
        ln -s "$rel_target" "$link_path"
        UPDATED+=("symlink $link_path -> $rel_target")
    elif [[ -e "$link_path" ]]; then
        log "ERROR: $link_path exists but is not a symlink. Manual intervention required."
        return 1
    else
        ln -s "$rel_target" "$link_path"
        CREATED+=("symlink $link_path -> $rel_target")
    fi
}

# Remove a path only if it is a symlink (never delete real files)
remove_if_symlink() {
    local path="$1"
    if [[ -L "$path" ]]; then
        rm "$path"
        REMOVED+=("symlink $path")
    fi
}

# Remove a directory only if it is empty
remove_if_empty_dir() {
    local dir="$1"
    if [[ -d "$dir" ]] && [[ ! -L "$dir" ]]; then
        local count
        count="$(find "$dir" -mindepth 1 -maxdepth 1 | wc -l)"
        if [[ "$count" -eq 0 ]]; then
            rmdir "$dir"
            REMOVED+=("empty dir $dir")
        fi
    fi
}

# ------------------------------------------------------------------------------
# Pre-flight checks
# ------------------------------------------------------------------------------

if [[ ! -d "$HUB_DIR" ]]; then
    log "ERROR: Hub directory does not exist: $HUB_DIR"
    exit 1
fi

# ------------------------------------------------------------------------------
# 1. Generate client-specific agent files
# ------------------------------------------------------------------------------

# The canonical header has shared name/description fields and two indented
# client sections. Preserve YAML verbatim rather than requiring a YAML package.
# This deliberately supports only the documented hub header layout.
python3 - "$HUB_DIR" <<'PYEOF'
from pathlib import Path
import re
import sys

hub = Path(sys.argv[1])
marker = '<!-- Generated by sync-hub.sh; do not edit this file. -->'
outputs = {}
for source in sorted((hub / 'agents').glob('*.md')):
    text = source.read_text()
    match = re.fullmatch(r'---\n(.*?)\n---\n(.*)', text, re.S)
    if not match:
        raise SystemExit(f'ERROR: Missing agent frontmatter: {source}')
    header, body = match.groups()
    common = []
    sections = {'opencode': [], 'vscode': []}
    section = None
    for line in header.splitlines():
        if not line.strip():
            continue
        if line in ('opencode:', 'vscode:'):
            section = line[:-1]
        elif line.startswith('  ') and section:
            sections[section].append(line[2:])
        elif re.match(r'^(name|description):\s+\S', line):
            section = None
            common.append(line)
        else:
            raise SystemExit(f'ERROR: Unsupported hub header line in {source}: {line}')
    if not any(line.startswith('description:') for line in common):
        raise SystemExit(f'ERROR: Missing description: {source}')
    if not any(line.startswith('name:') for line in common):
        common.insert(0, f'name: {source.stem}')
    for client, fields in sections.items():
        if not fields:
            raise SystemExit(f'ERROR: Missing {client} section: {source}')
        directory = hub / client / 'agents'
        suffix = '.agent.md' if client == 'vscode' else '.md'
        outputs[directory / (source.stem + suffix)] = (
            '---\n' + '\n'.join(common + fields) + '\n---\n\n'
            + marker + '\n' + body
        )

# Validate all sources before touching generated files. Only replace symlinks
# or files bearing our marker; never overwrite an unrelated regular file.
for target in outputs:
    if target.exists() and not target.is_symlink() and marker not in target.read_text():
        raise SystemExit(f'ERROR: Refusing to overwrite unmanaged file: {target}')
for client in ('opencode', 'vscode'):
    directory = hub / client / 'agents'
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.iterdir():
        if old not in outputs and (
            old.is_symlink() or (old.is_file() and marker in old.read_text())
        ):
            old.unlink()
            print(f'[sync-hub] Removed obsolete agent: {old}')
for target, content in outputs.items():
    if target.is_symlink():
        target.unlink()
    if not target.exists() or target.read_text() != content:
        target.write_text(content)
        print(f'[sync-hub] Generated agent: {target}')
    else:
        print(f'[sync-hub] Verified agent: {target}')
PYEOF

# Migrate the former direct link to canonical agents through the same mapping
# helper that manages every other hub symlink.
# ------------------------------------------------------------------------------
# 2. Verify/create OpenCode symlinks
# ------------------------------------------------------------------------------

log "Syncing OpenCode symlinks..."

# ~/.config/opencode/AGENTS.md -> ../ai/AGENTS.md
ensure_symlink "${OPENCODE_DIR}/AGENTS.md" "../ai/AGENTS.md"

# ~/.config/opencode/agents -> ../ai/opencode/agents
ensure_symlink "${OPENCODE_DIR}/agents" "../ai/opencode/agents"

# ~/.config/opencode/skills -> ../ai/skills
ensure_symlink "${OPENCODE_DIR}/skills" "../ai/skills"

# ------------------------------------------------------------------------------
# 3. Verify/create VS Code consumable directory structure
# ------------------------------------------------------------------------------
#
# VS Code: consumes from ~/.config/ai/vscode/:
#   instructions/general.instructions.md is generated with applyTo: '**'
#   agents/*.agent.md are generated with VS Code frontmatter
#   skills/<skill-name> -> ../../skills/<skill-name>
# ------------------------------------------------------------------------------

log "Syncing VS Code: consumable directory..."

# General instructions need an applyTo header for automatic file matching.
python3 - "$HUB_DIR" <<'PYEOF'
from pathlib import Path
import sys

hub = Path(sys.argv[1])
target = hub / 'vscode/instructions/general.instructions.md'
marker = '<!-- Generated by sync-hub.sh; do not edit this file. -->'
content = "---\napplyTo: '**'\n---\n\n" + marker + '\n\n' + (hub / 'AGENTS.md').read_text()
if target.exists() and not target.is_symlink() and marker not in target.read_text():
    raise SystemExit(f'ERROR: Refusing to overwrite unmanaged file: {target}')
target.parent.mkdir(parents=True, exist_ok=True)
if target.is_symlink():
    target.unlink()
if not target.exists() or target.read_text() != content:
    target.write_text(content)
    print(f'[sync-hub] Generated instructions: {target}')
else:
    print(f'[sync-hub] Verified instructions: {target}')
PYEOF

# skills/<skill-name>/SKILL.md -> symlink the entire skill directory
# Both OpenCode and VS Code expect the same directory-per-skill format:
#   skills/<name>/SKILL.md
# Since the source is now in the correct format, we just symlink each skill directory.
if [[ -d "${HUB_DIR}/skills" ]]; then
    mkdir -p "${VSCODE_DIR}/skills"
    declare -A EXPECTED_SKILL_DIRS

    for skill_dir in "${HUB_DIR}/skills"/*/; do
        [[ -d "$skill_dir" ]] || continue
        skill_name="$(basename "$skill_dir")"
        vscode_skill_link="${VSCODE_DIR}/skills/${skill_name}"
        rel_target="../../skills/${skill_name}"
        EXPECTED_SKILL_DIRS["$skill_name"]=1
        ensure_symlink "$vscode_skill_link" "$rel_target"
    done

    # Clean up orphaned skill symlinks in vscode/skills/
    if [[ -d "${VSCODE_DIR}/skills" ]]; then
        for entry in "${VSCODE_DIR}/skills"/*; do
            [[ -e "$entry" || -L "$entry" ]] || continue
            entry_name="$(basename "$entry")"
            if [[ -z "${EXPECTED_SKILL_DIRS[$entry_name]+isset}" ]]; then
                remove_if_symlink "$entry"
            fi
        done
        remove_if_empty_dir "${VSCODE_DIR}/skills"
    fi
fi

# ------------------------------------------------------------------------------
# 4. Clean up dead symlinks in OpenCode directory
# ------------------------------------------------------------------------------

log "Cleaning up dead symlinks in OpenCode directory..."

if [[ -d "$OPENCODE_DIR" ]]; then
    while IFS= read -r -d '' dead; do
        remove_if_symlink "$dead"
    done < <(find "$OPENCODE_DIR" -maxdepth 1 -type l ! -exec test -e {} \; -print0 2>/dev/null || true)
fi

# ------------------------------------------------------------------------------
# 5. Clean up dead symlinks in VS Code consumable directory
# ------------------------------------------------------------------------------

log "Cleaning up dead symlinks in VS Code: consumable directory..."

if [[ -d "$VSCODE_DIR" ]]; then
    while IFS= read -r -d '' dead; do
        remove_if_symlink "$dead"
    done < <(find "$VSCODE_DIR" -type l ! -exec test -e {} \; -print0 2>/dev/null || true)
fi

# ------------------------------------------------------------------------------
# 6. Host settings are intentionally managed manually
# ------------------------------------------------------------------------------

log "VS Code settings left unchanged; see ${HUB_DIR}/README.md for host setup."

# ------------------------------------------------------------------------------
# 7. Report summary
# ------------------------------------------------------------------------------

echo ""
echo "========================================"
echo "  AI Hub Sync Complete"
echo "========================================"

if [[ ${#CREATED[@]} -gt 0 ]]; then
    echo ""
    echo "Created (${#CREATED[@]}):"
    printf '  - %s\n' "${CREATED[@]}"
fi

if [[ ${#UPDATED[@]} -gt 0 ]]; then
    echo ""
    echo "Updated (${#UPDATED[@]}):"
    printf '  - %s\n' "${UPDATED[@]}"
fi

if [[ ${#REMOVED[@]} -gt 0 ]]; then
    echo ""
    echo "Removed (${#REMOVED[@]}):"
    printf '  - %s\n' "${REMOVED[@]}"
fi

if [[ ${#VERIFIED[@]} -gt 0 ]]; then
    echo ""
    echo "Verified (${#VERIFIED[@]}):"
    printf '  - %s\n' "${VERIFIED[@]}"
fi

if [[ ${#CREATED[@]} -eq 0 && ${#UPDATED[@]} -eq 0 && ${#REMOVED[@]} -eq 0 && ${#VERIFIED[@]} -eq 0 ]]; then
    echo ""
    echo "Nothing to do — everything is already in sync."
fi

echo ""
echo "Done."
