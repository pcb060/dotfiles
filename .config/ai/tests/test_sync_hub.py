"""Exercise sync-hub.sh in isolated homes, never in the real host settings."""

import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest


SOURCE = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by sync-hub.sh; do not edit this file. -->'


class SyncHubTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(dir='/tmp/opencode')
        self.addCleanup(self.temporary.cleanup)
        self.home = Path(self.temporary.name)
        self.hub = self.home / '.config/ai'
        self.hub.mkdir(parents=True)
        for name in ('sync-hub.sh', 'AGENTS.md'):
            shutil.copy2(SOURCE / name, self.hub / name)
        for name in ('agents', 'skills'):
            shutil.copytree(SOURCE / name, self.hub / name)

    def sync(self, success=True):
        result = subprocess.run(
            ['bash', str(self.hub / 'sync-hub.sh')],
            env={**os.environ, 'HOME': str(self.home)},
            capture_output=True, text=True, check=False,
        )
        if success:
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0)
        return result

    def test_native_headers_and_shared_bodies(self):
        self.sync()
        for source in (self.hub / 'agents').glob('*.md'):
            source_body = source.read_text().split('\n---\n', 1)[1]
            for client, suffix in (('opencode', '.md'), ('vscode', '.agent.md')):
                target = self.hub / client / 'agents' / (source.stem + suffix)
                self.assertFalse(target.is_symlink())
                header, body = target.read_text().split('\n---\n', 1)
                self.assertEqual(body, '\n' + MARKER + '\n' + source_body)
                self.assertNotIn('\nopencode:', header)
                self.assertNotIn('\nvscode:', header)
                if client == 'opencode':
                    self.assertIn('\npermission:', header)
                    self.assertIn('\nmodel: opencode-go/', header)
                    self.assertNotIn('\ntools:', header)
                else:
                    self.assertIn('\ntools:', header)
                    self.assertNotIn('\npermission:', header)
                    self.assertNotIn('\nmodel:', header)
        tutor = (self.hub / 'vscode/agents/learning-tutor.agent.md').read_text()
        self.assertNotIn("'edit'", tutor.split('\n---\n', 1)[0])
        instructions = (self.hub / 'vscode/instructions/general.instructions.md').read_text()
        self.assertTrue(instructions.startswith("---\napplyTo: '**'\n---\n"))
        self.assertTrue(instructions.endswith((self.hub / 'AGENTS.md').read_text()))

    def test_settings_are_untouched_and_absence_is_allowed(self):
        self.sync()
        settings = self.home / '.config/Code/User/settings.json'
        self.assertFalse(settings.exists())
        settings.parent.mkdir(parents=True)
        content = '// host-owned JSONC\n{"chat.agentFilesLocations": {},}\n'
        settings.write_text(content)
        before = settings.stat().st_mtime_ns
        self.sync()
        self.assertEqual(settings.read_text(), content)
        self.assertEqual(settings.stat().st_mtime_ns, before)

    def test_idempotent_and_links_resolve(self):
        self.sync()
        files = [p for p in self.hub.rglob('*') if p.is_file() and not p.is_symlink()]
        before = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in files}
        self.sync()
        self.assertEqual(before, {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in files})
        for root in (self.hub, self.home / '.config/opencode'):
            for path in root.rglob('*'):
                if path.is_symlink():
                    self.assertTrue(path.exists(), str(path))
        self.assertEqual(
            (self.home / '.config/opencode/agents').resolve(),
            self.hub / 'opencode/agents',
        )

    def test_migrates_legacy_symlinks(self):
        opencode = self.home / '.config/opencode'
        opencode.mkdir(parents=True)
        (opencode / 'agents').symlink_to('../ai/agents')
        for source in (self.hub / 'agents').glob('*.md'):
            target = self.hub / 'vscode/agents' / (source.stem + '.agent.md')
            target.parent.mkdir(parents=True, exist_ok=True)
            target.symlink_to('../../agents/' + source.name)
        instructions = self.hub / 'vscode/instructions/general.instructions.md'
        instructions.parent.mkdir(parents=True)
        instructions.symlink_to('../../AGENTS.md')
        self.sync()
        self.assertFalse(instructions.is_symlink())
        self.assertEqual((opencode / 'agents').resolve(), self.hub / 'opencode/agents')
        self.assertTrue((self.hub / 'agents/learning-tutor.md').exists())

    def test_removes_obsolete_generated_agents_and_broken_skill_links(self):
        self.sync()
        (self.hub / 'agents/learning-tutor.md').unlink()
        obsolete = self.hub / 'vscode/skills/obsolete'
        obsolete.symlink_to('../../skills/obsolete')
        unrelated = self.hub / 'vscode/agents/notes.txt'
        unrelated.write_text('Do not delete me.\n')
        self.sync()
        self.assertFalse((self.hub / 'opencode/agents/learning-tutor.md').exists())
        self.assertFalse((self.hub / 'vscode/agents/learning-tutor.agent.md').exists())
        self.assertFalse(obsolete.is_symlink())
        self.assertTrue(unrelated.exists())

    def test_refuses_to_overwrite_unmanaged_agents(self):
        target = self.hub / 'vscode/agents/learning-tutor.agent.md'
        target.parent.mkdir(parents=True)
        target.write_text('User-owned content\n')
        result = self.sync(success=False)
        self.assertIn('Refusing to overwrite', result.stderr)
        self.assertEqual(target.read_text(), 'User-owned content\n')

    def test_rejects_bad_source_before_generating_anything(self):
        source = self.hub / 'agents/learning-tutor.md'
        source.write_text('---\ndescription: Tutor\nunknown: true\n---\nBody\n')
        result = self.sync(success=False)
        self.assertIn('Unsupported hub header', result.stderr)
        self.assertFalse((self.hub / 'opencode').exists())
        self.assertFalse((self.hub / 'vscode').exists())


if __name__ == '__main__':
    unittest.main()
